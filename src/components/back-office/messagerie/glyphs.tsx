export function ChannelIcon({ channel, ...props }: { channel: Channel } & GlyphProps) {
  switch (channel) {
    case "call":
      return <PhoneGlyph {...props} />;
    case "sms":
      return <SmsGlyph {...props} />;
    case "whatsapp":
      return <WhatsAppGlyph {...props} />;
    case "chat":
      return <ChatGlyph {...props} />;
  }
}
